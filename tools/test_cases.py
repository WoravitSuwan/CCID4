HEAD = ["รหัส", "หมวด", "กรณีทดสอบ", "ผู้ใช้", "ขั้นตอน", "ผลที่คาดหวัง", "ทดสอบอัตโนมัติ",
        "ผลที่ได้จริง", "ผ่าน/ไม่ผ่าน", "ผู้ทดสอบ", "วันที่ทดสอบ", "หมายเหตุ"]


def rows():
    for gi, (group, cases) in enumerate(CASES, start=1):
        for ci, (name, who, steps, expected, auto) in enumerate(cases, start=1):
            yield [f"TC-{gi:02d}-{ci:02d}", group, name, who, steps, expected, auto or "ทดสอบด้วยมือ"]


def write_markdown(path: Path):
    lines = ["# แผนทดสอบระบบออกหมายเรียก (Test cases)", "",
             "สร้างจาก `tools/test_cases.py` · ช่อง \"อัตโนมัติ\" คือเทสต์ใน `tests/` ที่ตรวจเรื่องเดียวกันทุกครั้งที่แก้โค้ด "
             "(รัน `python -m pytest`)", ""]
    for gi, (group, cases) in enumerate(CASES, start=1):
        lines += [f"## {gi}. {group}", "", "| รหัส | กรณีทดสอบ | ผู้ใช้ | ขั้นตอน | ผลที่คาดหวัง | อัตโนมัติ |",
                  "|---|---|---|---|---|---|"]
        for ci, (name, who, steps, expected, auto) in enumerate(cases, start=1):
            cells = [f"TC-{gi:02d}-{ci:02d}", name, who, steps, expected, auto or "ทดสอบด้วยมือ"]
            lines.append("| " + " | ".join(c.replace("|", "/") for c in cells) + " |")
        lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def write_excel(path: Path):
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill
    from openpyxl.worksheet.datavalidation import DataValidation

    wb = Workbook()
    ws = wb.active
    ws.title = "Test cases"
    ws.append(HEAD)
    for r in rows():
        ws.append(r + ["", "", "", "", ""])
    widths = [11, 22, 30, 14, 48, 48, 30, 30, 12, 14, 13, 24]
    for i, w in enumerate(widths):
        ws.column_dimensions[chr(65 + i)].width = w
    for cell in ws[1]:
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = PatternFill("solid", fgColor="334155")
    for row in ws.iter_rows(min_row=2):
        for cell in row:
            cell.alignment = Alignment(wrap_text=True, vertical="top")
    ws.freeze_panes = "C2"
    ws.auto_filter.ref = ws.dimensions
    status = DataValidation(type="list", formula1='"ผ่าน,ไม่ผ่าน,ยังไม่ทดสอบ"', allow_blank=True)
    ws.add_data_validation(status)
    status.add(f"I2:I{ws.max_row}")
    summary = wb.create_sheet("สรุป")
    summary.append(["หมวด", "จำนวนกรณี", "ผ่าน", "ไม่ผ่าน", "ยังไม่ทดสอบ"])
    for group, cases in CASES:
        r = summary.max_row + 1
        summary.append([group, len(cases), f'=COUNTIFS(\'Test cases\'!B:B,A{r},\'Test cases\'!I:I,"ผ่าน")',
                        f'=COUNTIFS(\'Test cases\'!B:B,A{r},\'Test cases\'!I:I,"ไม่ผ่าน")', f"=B{r}-C{r}-D{r}"])
    n = summary.max_row
    summary.append(["รวม", f"=SUM(B2:B{n})", f"=SUM(C2:C{n})", f"=SUM(D2:D{n})", f"=SUM(E2:E{n})"])
    for cell in summary[1] + summary[summary.max_row]:
        cell.font = Font(bold=True)
    summary.column_dimensions["A"].width = 30
    wb.save(path)


